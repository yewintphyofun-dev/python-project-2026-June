# set
# unorder ဖြစ်ပြီး ထပ်နေတာမျိုးမရှိ
course = {"Myanmar","English","Math","Physics","Math"}
print(course)

# discard ဆိုတာ ဖျက်ထုတ်တာ
course.discard("Math")
print(course)

# clear() ဆိုတာ အလွတ်ဖြစ်အောင်လုပ်တာ
course.clear()
print(course)

# del ဆိုတာကတော့ set တစ်ခုလုံးကို ဖျက်ပစ်လိုက်တာ
del course

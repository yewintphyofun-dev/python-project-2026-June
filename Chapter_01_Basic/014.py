import random
print(random.randrange(4))
#   0~3 ကြား random ကိန်းတစ်လုံးကို ထုတ်ပေးလိမ့်မယ်

print(random.randrange(2,7))
#   2 ကနေ 6 အတွင်း random ကိန်းတစ်ခုကို ထုတ်ပေး

print(random.randrange(10,100,10))
#   10 ကနေ 100 အတွင်းထုတ်၊ ဒါပေမဲ့ ကြားထဲမှာ 10 စီကျော်သွားမယ်
#   10,20,30,40 ,....ထဲကနေ တစ်ခုခုကိုထုတ်